await page.getByRole('heading', { name: 'Gracias por escribirnos.' }).waitFor();
await page.getByRole('button', { name: 'Listo', exact: true }).click();
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
console.log('PASS: desktop booking, lookup, PDF download, cancellation, tabs, gallery, FAQ and contact');
const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, isMobile: true, hasTouch: true });
mobile.on('pageerror', (error) => errors.push(error.message));
await mobile.goto(base, { waitUntil: 'networkidle' });
await mobile.evaluate(() => document.fonts.ready);
await mobile.screenshot({ path: 'artifacts/mobile.png', fullPage: false });
assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
await mobile.getByRole('button', { name: 'Abrir menú' }).click();
