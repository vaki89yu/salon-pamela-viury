console.log('All browser tests passed without runtime errors.');
await page.setViewportSize({ width: 1440, height: 1000 });
await page.goto(base, { waitUntil: 'networkidle' });
for (const [id, file] of [['servicios','services'], ['nosotras','about'], ['galeria','gallery'], ['contacto','location']]) {
  const section = page.locator(`#${id}`);
  await section.scrollIntoViewIfNeeded(); await page.waitForTimeout(850);
  await section.screenshot({ path: `artifacts/${file}.png` });
}
await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' })); await page.waitForTimeout(400);
await page.screenshot({ path: 'artifacts/desktop.png' });
for (const width of [360, 390, 768, 1024, 1440]) {
  await page.setViewportSize({ width, height: 900 });
  await page.goto(base, { waitUntil: 'networkidle' });
  const metrics = await page.evaluate(() => ({ width: innerWidth, document: document.documentElement.scrollWidth, font: getComputedStyle(document.querySelector('.hero-description')).fontSize, color: getComputedStyle(document.querySelector('.header-book')).backgroundColor }));
  assert.ok(metrics.document <= metrics.width, `Horizontal overflow at ${width}px: ${JSON.stringify(metrics)}`);
  console.log(`PASS: ${width}px layout, hero text ${metrics.font}, primary ${metrics.color}`);
}
await browser.close();
