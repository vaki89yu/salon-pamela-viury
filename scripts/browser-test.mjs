await page.getByRole('textbox', { name: 'Nombre completo' }).fill('Prueba de navegador');
await page.getByRole('textbox', { name: 'Teléfono de 10 dígitos' }).fill('6560000088');
await page.getByRole('textbox', { name: 'Correo electrónico' }).fill('navegador@example.com');
await page.locator('input[name="consent"]').check();
await page.getByRole('button', { name: 'Confirmar mi cita', exact: true }).click();
await page.getByRole('heading', { name: 'Su cita está confirmada' }).waitFor();
await page.screenshot({ path: 'artifacts/booking.png' });
const folio = await page.locator('.folio strong').textContent(); assert.match(folio, /^PV-/);
const downloadPromise = page.waitForEvent('download');
await page.getByRole('button', { name: 'Descargar comprobante PDF' }).click();
const download = await downloadPromise; assert.match(download.suggestedFilename(), /\.pdf$/);
await page.getByRole('button', { name: 'Necesito cancelar mi cita' }).click();
