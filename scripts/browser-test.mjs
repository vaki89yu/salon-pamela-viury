await page.getByRole('heading', { name: 'Su cita está cancelada.' }).waitFor();
await page.getByRole('button', { name: 'Cerrar ventana' }).click();
await page.getByRole('button', { name: 'Mi cita', exact: true }).click();
await page.getByRole('textbox', { name: 'Folio de su cita' }).fill(folio);
await page.getByRole('textbox', { name: 'Teléfono de su reserva' }).fill('6560000088');
await page.getByRole('button', { name: 'Consultar mi cita', exact: true }).click();
await page.getByRole('heading', { name: 'Su cita está cancelada.' }).waitFor();
await page.keyboard.press('Escape');
await page.getByRole('tab', { name: 'Uñas', exact: true }).click();
assert.equal(await page.locator('.service-card').count(), 1);
await page.getByRole('tab', { name: 'Todos', exact: true }).click();
assert.equal(await page.locator('.service-card').count(), 6);
await page.getByRole('tab', { name: 'Los favoritos', exact: false }).click();
await page.locator('.gallery-item').first().click();
await page.getByRole('button', { name: 'Siguiente imagen' }).click();
await page.keyboard.press('Escape');
await page.getByRole('button', { name: 'Abrir ayuda y contacto' }).click();
await page.getByText('¿Tengo que pagar al reservar?', { exact: true }).click();
await page.keyboard.press('Escape');
await page.getByRole('button', { name: 'Enviar una consulta', exact: true }).click();
await page.getByRole('textbox', { name: 'Nombre y apellidos' }).fill('Prueba de contacto');
await page.getByRole('textbox', { name: 'Correo electrónico', exact: false }).fill('contacto@example.com');
