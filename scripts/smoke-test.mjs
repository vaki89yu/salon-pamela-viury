import assert from 'node:assert/strict';
import { PDFDocument } from 'pdf-lib';
const base = process.env.TEST_BASE_URL || 'http://localhost:3000';
async function api(path, options) {
  const response = await fetch(`${base}${path}`, options);
  const body = response.headers.get('content-type')?.includes('application/json') ? await response.json() : await response.arrayBuffer();
  return { response, body };
}
const json = (body, method = 'POST') => ({ method, headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
const day = new Date(); day.setUTCDate(day.getUTCDate() + 20); if (day.getUTCDay() === 0) day.setUTCDate(day.getUTCDate() + 1);
const date = day.toISOString().slice(0, 10);
let result = await api(`/api/availability?date=${date}&service=corte&stylist=valeria`);
assert.equal(result.response.status, 200); assert.ok(result.body.slots.length > 0);
const time = result.body.slots[0];
const data = { name: 'Prueba automatica Pamela Viury', phone: '6560000099', email: 'prueba@example.com', serviceId: 'corte', stylistId: 'valeria', date, time, notes: 'Reserva de verificación técnica. Se cancela al terminar.', consent: true };
result = await api('/api/appointments', json(data)); assert.equal(result.response.status, 201, JSON.stringify(result.body));
const appointment = result.body.appointment;
assert.match(appointment.folio, /^PV-\d{6}-[A-F0-9]{8}$/);
assert.ok(appointment.accessToken);
console.log('PASS: booking saved with unique folio');
result = await api('/api/appointments', json(data)); assert.equal(result.response.status, 409);
console.log('PASS: overlapping appointments rejected');
result = await api(`/api/availability?date=${date}&service=corte&stylist=valeria`); assert.ok(!result.body.slots.includes(time));
result = await api('/api/appointments/lookup', json({ folio: appointment.folio, phone: '6560000001' })); assert.equal(result.response.status, 404);
result = await api('/api/appointments/lookup', json({ folio: appointment.folio.toLowerCase(), phone: data.phone })); assert.equal(result.response.status, 200); assert.equal(result.body.appointment.name, data.name);
console.log('PASS: private lookup requires matching phone');
result = await api(`/api/appointments/${appointment.folio}/pdf`); assert.equal(result.response.status, 401);
result = await api(`/api/appointments/${appointment.folio}/pdf?token=${appointment.accessToken}`); assert.equal(result.response.status, 200); assert.equal(result.response.headers.get('content-type'), 'application/pdf'); assert.equal(Buffer.from(result.body).subarray(0, 4).toString(), '%PDF');
const receipt = await PDFDocument.load(result.body);
assert.equal(receipt.getPageCount(), 1);
assert.match(receipt.getTitle(), new RegExp(appointment.folio));
assert.ok(result.body.byteLength > 30_000, `Receipt PDF looks too light: ${result.body.byteLength} bytes`);
console.log(`PASS: private illustrated receipt PDF generated (${Math.round(result.body.byteLength / 1024)} KB)`);
result = await api('/api/catalog/pdf'); assert.equal(result.response.status, 200);
const catalog = await PDFDocument.load(result.body);
assert.equal(catalog.getPageCount(), 4);
assert.match(catalog.getTitle(), /Pamela Viury/);
assert.equal(catalog.getAuthor(), 'Salón de Belleza Pamela Viury');
assert.ok(result.body.byteLength > 120_000, `Catalog PDF looks too light: ${result.body.byteLength} bytes`);
console.log(`PASS: 4-page illustrated catalogue PDF generated (${Math.round(result.body.byteLength / 1024)} KB)`);
result = await api(`/api/appointments/${appointment.folio}`, json({ accessToken: appointment.accessToken }, 'PATCH')); assert.equal(result.response.status, 200); assert.equal(result.body.appointment.status, 'cancelled');
result = await api(`/api/availability?date=${date}&service=corte&stylist=valeria`); assert.ok(result.body.slots.includes(time));
console.log('PASS: cancellation releases time slot');
result = await api('/api/appointments', json(data)); assert.equal(result.response.status, 201, JSON.stringify(result.body)); const second = result.body.appointment;
result = await api(`/api/appointments/${second.folio}`, json({ accessToken: second.accessToken }, 'PATCH')); assert.equal(result.response.status, 200);
console.log('PASS: previously cancelled slot can be reserved again');
result = await api('/api/appointments', json({ ...data, time: '10:90' })); assert.equal(result.response.status, 400);
result = await api('/api/appointments', json({ ...data, consent: false })); assert.equal(result.response.status, 400);
result = await api('/api/appointments', json({ ...data, stylistId: 'daniela' })); assert.equal(result.response.status, 400);
result = await api('/api/appointments/lookup', json(null)); assert.equal(result.response.status, 400);
console.log('PASS: malformed time, missing consent, incompatible specialist and invalid lookup rejected');
result = await api('/api/contact', json({ name: 'Verificacion Pamela Viury', email: 'prueba@example.com', message: 'Mensaje automático de verificación del formulario de contacto.', consent: true })); assert.equal(result.response.status, 201);
console.log('PASS: contact inquiry saved');
console.log('All fullstack smoke tests passed.');
